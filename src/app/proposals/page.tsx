"use client";

import { useState } from "react";
import Link from "next/link";
import {
  TrendingUp,
  Lightbulb,
  Filter,
  Bot,
  Building2,
  ArrowUpRight,
  ChevronRight,
} from "lucide-react";
import {
  Select,
  SelectContent,
  SelectItem,
  SelectTrigger,
  SelectValue,
} from "@/components/ui/select";
import { CategoryBadge } from "@/components/shared/CategoryBadge";
import { StatusBadge } from "@/components/shared/StatusBadge";
import { DemoNotice } from "@/components/shared/DemoNotice";
import { DEMO_PROPOSALS, DEMO_ISSUES } from "@/lib/demo-data";
import { CATEGORY_LABELS } from "@/types";
import { formatRelativeDate } from "@/lib/utils";
import type { IssueCategory, ProposalStatus } from "@/types";

const statusOptions: { value: ProposalStatus | "all"; label: string }[] = [
  { value: "all", label: "All Statuses" },
  { value: "proposed", label: "Proposed" },
  { value: "under_consideration", label: "Under Consideration" },
  { value: "approved", label: "Approved" },
  { value: "implemented", label: "Implemented" },
];

export default function ProposalsPage() {
  const [categoryFilter, setCategoryFilter] = useState<string>("all");
  const [statusFilter, setStatusFilter] = useState<string>("all");
  const [sortBy, setSortBy] = useState<"votes" | "recent">("votes");
  const [votedIds, setVotedIds] = useState<Set<string>>(new Set());

  const filtered = DEMO_PROPOSALS.filter((p) => {
    const matchCat = categoryFilter === "all" || p.category === categoryFilter;
    const matchStatus = statusFilter === "all" || p.status === statusFilter;
    return matchCat && matchStatus;
  }).sort((a, b) =>
    sortBy === "votes"
      ? b.votes - a.votes
      : new Date(b.createdAt).getTime() - new Date(a.createdAt).getTime()
  );

  const handleVote = (id: string) => {
    setVotedIds((prev) => {
      const next = new Set(prev);
      if (next.has(id)) {
        next.delete(id);
      } else {
        next.add(id);
      }
      return next;
    });
  };

  const categories = Object.entries(CATEGORY_LABELS) as [
    IssueCategory,
    string
  ][];

  return (
    <div className="max-w-6xl mx-auto px-4 py-10">
      {/* Header */}
      <div className="flex flex-wrap items-start justify-between gap-4 mb-8">
        <div>
          <h1 className="text-2xl font-bold text-civic-text flex items-center gap-2">
            <Lightbulb className="w-6 h-6 text-civic-lime" />
            Community Proposals
          </h1>
          <p className="text-civic-text-muted mt-1">
            Solutions proposed by the community and surfaced by AI analysis.
            Vote for proposals you support.
          </p>
        </div>
        <DemoNotice inline />
      </div>

      {/* How it works */}
      <div className="glass rounded-2xl p-5 border border-white/7 mb-8">
        <div className="flex items-start gap-3">
          <Bot className="w-5 h-5 text-purple-400 flex-shrink-0 mt-0.5" />
          <div>
            <h2 className="text-sm font-semibold text-civic-text mb-1">
              How Proposals Work
            </h2>
            <p className="text-sm text-civic-text-muted leading-relaxed">
              Proposals are submitted by community members or generated by
              CivicVoice AI based on clusters of related issues. AI helps
              organize and analyze — the community determines priorities by
              voting. All AI-generated proposals are clearly labeled.
            </p>
          </div>
        </div>
      </div>

      {/* Filters */}
      <div className="flex flex-wrap items-center gap-3 mb-6">
        <div className="flex items-center gap-1.5 text-sm text-civic-text-muted">
          <Filter className="w-4 h-4" />
          Filter:
        </div>
        <Select value={categoryFilter} onValueChange={setCategoryFilter}>
          <SelectTrigger className="w-44 h-9">
            <SelectValue placeholder="Category" />
          </SelectTrigger>
          <SelectContent>
            <SelectItem value="all">All Categories</SelectItem>
            {categories.map(([value, label]) => (
              <SelectItem key={value} value={value}>
                {label}
              </SelectItem>
            ))}
          </SelectContent>
        </Select>
        <Select value={statusFilter} onValueChange={setStatusFilter}>
          <SelectTrigger className="w-48 h-9">
            <SelectValue placeholder="Status" />
          </SelectTrigger>
          <SelectContent>
            {statusOptions.map(({ value, label }) => (
              <SelectItem key={value} value={value}>
                {label}
              </SelectItem>
            ))}
          </SelectContent>
        </Select>
        <div className="ml-auto flex border border-white/10 rounded-lg overflow-hidden">
          {(["votes", "recent"] as const).map((s) => (
            <button
              key={s}
              onClick={() => setSortBy(s)}
              className={`px-3 py-1.5 text-xs transition-colors capitalize ${
                sortBy === s
                  ? "bg-civic-cyan/15 text-civic-cyan"
                  : "text-civic-text-muted hover:text-civic-text hover:bg-white/5"
              } ${s === "recent" ? "border-l border-white/10" : ""}`}
            >
              {s === "votes" ? "Most Votes" : "Most Recent"}
            </button>
          ))}
        </div>
      </div>

      {/* Proposal list */}
      <div className="space-y-4">
        {filtered.map((proposal) => {
          const hasVoted = votedIds.has(proposal.id);
          const displayVotes = hasVoted ? proposal.votes + 1 : proposal.votes;
          const relatedIssues = DEMO_ISSUES.filter((i) =>
            proposal.relatedIssueIds.includes(i.id)
          );

          return (
            <div
              key={proposal.id}
              className="glass rounded-2xl p-6 border border-white/7 hover:border-white/12 transition-all duration-200"
            >
              <div className="flex flex-col sm:flex-row sm:items-start gap-4">
                {/* Vote button */}
                <div className="flex sm:flex-col items-center gap-3 sm:gap-1 sm:w-16 flex-shrink-0">
                  <button
                    onClick={() => handleVote(proposal.id)}
                    className={`w-12 h-12 rounded-xl border flex flex-col items-center justify-center transition-all duration-200 group ${
                      hasVoted
                        ? "bg-civic-lime/15 border-civic-lime/40 text-civic-lime glow-cyan"
                        : "border-white/10 bg-white/5 text-civic-text-muted hover:border-civic-lime/30 hover:bg-civic-lime/10 hover:text-civic-lime"
                    }`}
                  >
                    <ArrowUpRight
                      className={`w-5 h-5 transition-transform ${hasVoted ? "" : "group-hover:-translate-y-0.5 group-hover:translate-x-0.5"}`}
                    />
                  </button>
                  <span
                    className={`text-lg font-bold tabular-nums ${
                      hasVoted ? "text-civic-lime" : "text-civic-text"
                    }`}
                  >
                    {displayVotes}
                  </span>
                  <span className="text-xs text-civic-text-muted">votes</span>
                </div>

                {/* Content */}
                <div className="flex-1 min-w-0">
                  <div className="flex flex-wrap items-center gap-2 mb-2">
                    <CategoryBadge category={proposal.category} size="sm" />
                    <StatusBadge
                      status={proposal.status}
                      type="proposal"
                    />
                    {proposal.aiGenerated && (
                      <span className="inline-flex items-center gap-1 text-xs text-purple-400 bg-purple-400/10 border border-purple-400/20 rounded-full px-2 py-0.5">
                        <Bot className="w-3 h-3" />
                        AI-assisted
                      </span>
                    )}
                  </div>

                  <h2 className="text-base font-bold text-civic-text mb-2 leading-tight">
                    {proposal.title}
                  </h2>

                  <p className="text-sm text-civic-text-muted leading-relaxed mb-3">
                    {proposal.description}
                  </p>

                  {/* Impact */}
                  <div className="flex items-start gap-2 glass rounded-lg px-3 py-2 mb-3">
                    <TrendingUp className="w-3.5 h-3.5 text-civic-lime flex-shrink-0 mt-0.5" />
                    <p className="text-xs text-civic-lime">{proposal.estimatedImpact}</p>
                  </div>

                  {/* Footer */}
                  <div className="flex flex-wrap items-center gap-4 text-xs text-civic-text-muted">
                    {proposal.implementingBody && (
                      <div className="flex items-center gap-1">
                        <Building2 className="w-3 h-3" />
                        {proposal.implementingBody}
                      </div>
                    )}
                    <span>Proposed {formatRelativeDate(proposal.createdAt)}</span>
                    {relatedIssues.length > 0 && (
                      <div className="flex items-center gap-1 ml-auto">
                        <span>
                          Related to {relatedIssues.length} issue
                          {relatedIssues.length !== 1 ? "s" : ""}:
                        </span>
                        <div className="flex gap-1">
                          {relatedIssues.slice(0, 2).map((ri) => (
                            <Link
                              key={ri.id}
                              href={`/issues/${ri.id}`}
                              className="text-civic-cyan hover:underline flex items-center gap-0.5"
                            >
                              {ri.title.split(" ").slice(0, 3).join(" ")}…
                              <ChevronRight className="w-3 h-3" />
                            </Link>
                          ))}
                        </div>
                      </div>
                    )}
                  </div>
                </div>
              </div>
            </div>
          );
        })}
      </div>

      {filtered.length === 0 && (
        <div className="text-center py-16 glass rounded-2xl border border-white/7">
          <Lightbulb className="w-10 h-10 text-civic-text-muted mx-auto mb-3" />
          <p className="text-civic-text-muted">No proposals match your filters.</p>
        </div>
      )}
    </div>
  );
}
